"""
Final evaluation report generation for AutoMR.

Collects experiment artifacts generated by the AutoMR
pipeline and produces a single consolidated JSON report.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Optional

import numpy as np


class FinalEvaluationReport:
    """
    Generate a consolidated experiment report.

    The report is intentionally artifact-based: it reads
    outputs already produced by the AutoMR pipeline instead
    of rerunning model inference or metamorphic testing.
    """

    def __init__(self, output_dir="results"):

        self.output_dir = Path(output_dir)

    # ==================================================
    # JSON utilities
    # ==================================================

    @staticmethod
    def _to_json_safe(value):
        """
        Convert NumPy and other non-standard values into
        JSON-serializable Python values.
        """

        if isinstance(value, dict):

            return {
                str(key): FinalEvaluationReport._to_json_safe(val)
                for key, val in value.items()
            }

        if isinstance(value, (list, tuple)):

            return [
                FinalEvaluationReport._to_json_safe(item)
                for item in value
            ]

        if isinstance(
            value,
            (
                np.integer,
                np.int64,
                np.int32,
            ),
        ):

            return int(value)

        if isinstance(
            value,
            (
                np.floating,
                np.float64,
                np.float32,
            ),
        ):

            return float(value)

        if isinstance(value, np.ndarray):

            return value.tolist()

        return value

    # ==================================================
    # Artifact loading
    # ==================================================

    def _load_json(
        self,
        filename: str,
    ) -> Optional[Dict[str, Any]]:

        path = self.output_dir / filename

        if not path.exists():

            return None

        try:

            with path.open(
                "r",
                encoding="utf-8",
            ) as file:

                return json.load(file)

        except Exception:

            return None

    def _list_available_artifacts(self):

        if not self.output_dir.exists():

            return []

        return sorted(
            [
                path.name
                for path in self.output_dir.iterdir()
                if path.is_file()
            ]
        )

    # ==================================================
    # Main report generation
    # ==================================================

    def generate(
        self,
        test_summary=None,
        epsilon_summary=None,
        benchmark_results=None,
        additional_results=None,
    ) -> Dict[str, Any]:
        """
        Generate a consolidated final evaluation report.

        Parameters
        ----------
        test_summary:
            Overall AutoMR pass/fail summary.

        epsilon_summary:
            Output from EpsilonSummary.

        benchmark_results:
            Optional standard vs HPC benchmark results.

        additional_results:
            Optional additional analysis results.

        Returns
        -------
        dict
            Consolidated evaluation report.
        """

        report = {
            "report_generated_at": (
                datetime.now().isoformat()
            ),

            "output_directory": str(
                self.output_dir
            ),

            "test_summary": (
                test_summary
                if test_summary is not None
                else self._load_json(
                    "test_summary.json"
                )
            ),

            "baseline": {
                "metrics": self._load_json(
                    "baseline_metrics.json"
                ),

                "dataset_info": self._load_json(
                    "dataset_info.json"
                ),
            },

            "decoder_health": self._load_json(
                "decoder_health.json"
            ),

            "epsilon_analysis": (
                epsilon_summary
                if epsilon_summary is not None
                else self._load_json(
                    "epsilon_summary.json"
                )
            ),

            "benchmark": (
                benchmark_results
                if benchmark_results is not None
                else self._load_json(
                    "benchmark_results.json"
                )
            ),

            "additional_analysis": (
                additional_results
                if additional_results is not None
                else {}
            ),

            "available_artifacts": (
                self._list_available_artifacts()
            ),
        }

        return self._to_json_safe(report)

    # ==================================================
    # Save
    # ==================================================

    def save(
        self,
        report: Dict[str, Any],
        filename="final_evaluation_report.json",
    ) -> Path:
        """
        Save the final consolidated report.
        """

        self.output_dir.mkdir(
            parents=True,
            exist_ok=True,
        )

        output_path = (
            self.output_dir
            / filename
        )

        with output_path.open(
            "w",
            encoding="utf-8",
        ) as file:

            json.dump(
                self._to_json_safe(report),
                file,
                indent=4,
            )

        return output_path

    # ==================================================
    # Generate and save
    # ==================================================

    def generate_and_save(
        self,
        test_summary=None,
        epsilon_summary=None,
        benchmark_results=None,
        additional_results=None,
    ) -> Dict[str, Any]:
        """
        Generate and save the consolidated report.
        """

        report = self.generate(
            test_summary=test_summary,
            epsilon_summary=epsilon_summary,
            benchmark_results=benchmark_results,
            additional_results=additional_results,
        )

        self.save(report)

        return report